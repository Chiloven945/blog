#!/usr/bin/env node
/**
 * Split the self-hosted CJK fonts into unicode-range chunks.
 *
 * The browser only downloads the chunks that contain characters used by the
 * current page, instead of the whole 8-10 MB CJK font. The full source fonts
 * live in `assets/font-sources/` (never deployed); generated chunks and the
 * matching CSS live in `public/fonts/slices/` and
 * `app/assets/css/fonts.generated.css`.
 *
 * Run after changing a source font, or after adding content that introduces
 * characters not covered by the current chunks:
 *
 *   bun run fonts:split
 *
 * `cn-font-split` must be invoked with Node (the Bun build of the package
 * cannot load its native library on every platform).
 */
import {execFileSync} from 'node:child_process'
import {
    cpSync,
    mkdirSync,
    mkdtempSync,
    readdirSync,
    readFileSync,
    rmSync,
    writeFileSync
} from 'node:fs'
import {tmpdir} from 'node:os'
import {basename, dirname, join, relative} from 'node:path'
import {fileURLToPath} from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cli = join(root, 'node_modules', 'cn-font-split', 'dist', 'cli.js')
const outRoot = join(root, 'public', 'fonts', 'slices')
const cssFile = join(root, 'app', 'assets', 'css', 'fonts.generated.css')

/** @type {{key: string, family: string, weight: string, input: string, license: string}[]} */
const fonts = [
    {
        key: 'source-han-sans',
        family: 'Source Han Sans CN',
        weight: '250 900',
        input: 'assets/font-sources/source-han-sans/SourceHanSansCN-VF.woff2',
        license: 'assets/font-sources/source-han-sans/source-han-sans-OFL.txt',
    },
    {
        key: 'source-han-serif',
        family: 'Source Han Serif CN',
        weight: '250 900',
        input: 'assets/font-sources/source-han-serif/SourceHanSerifCN-VF.woff2',
        license: 'assets/font-sources/source-han-serif/source-han-serif-OFL.txt',
    },
    {
        key: 'sarasa-mono-cl',
        family: 'Sarasa Mono CL',
        weight: '400',
        input: 'assets/font-sources/sarasa-mono-cl/SarasaMonoCL-Regular.woff2',
        license: 'assets/font-sources/sarasa-mono-cl/sarasa-gothic-OFL.txt',
    },
]

function runSplit(font) {
    const tmp = mkdtempSync(join(tmpdir(), 'blog-font-split-'))
    try {
        execFileSync(process.execPath, [
            cli,
            'run',
            '-i', join(root, font.input),
            '-o', tmp,
            '--css.fontFamily', font.family,
            '--css.fontWeight', font.weight,
            '--css.fontStyle', 'normal',
            '--css.fontDisplay', 'swap',
            '--testHtml', 'false',
        ], {stdio: 'inherit'})

        const css = readFileSync(join(tmp, 'result.css'), 'utf8')
        const chunks = readdirSync(tmp).filter(file => file.endsWith('.woff2'))

        const target = join(outRoot, font.key)
        rmSync(target, {recursive: true, force: true})
        mkdirSync(target, {recursive: true})
        for (const chunk of chunks) {
            cpSync(join(tmp, chunk), join(target, chunk))
        }
        // Keep the OFL license next to the deployed chunk files.
        cpSync(join(root, font.license), join(target, basename(font.license)))

        // Absolute public URLs (Vite must not try to resolve these relative to
        // app/assets/css), and no `local()` source so the generated webfont is
        // always used consistently.
        const blocks = css.match(/@font-face\{[^}]*\}/g) ?? []
        const generated = blocks.map(block => block
            .replace(/src:local\("[^"]*"\),/, 'src:')
            .replaceAll('url("./', `url("/fonts/slices/${font.key}/`),
        )

        const bytes = chunks.reduce((sum, chunk) => {
            return sum + readFileSync(join(target, chunk)).byteLength
        }, 0)

        return {
            key: font.key,
            family: font.family,
            blocks: generated.length,
            chunks: chunks.length,
            bytes,
            generated,
        }
    } finally {
        rmSync(tmp, {recursive: true, force: true})
    }
}

rmSync(outRoot, {recursive: true, force: true})
mkdirSync(outRoot, {recursive: true})

const results = fonts.map(runSplit)

const css = [
    '/* ==========================================================================',
    '   fonts.generated.css — generated by tools/split-fonts.mjs',
    '   ==========================================================================',
    '   CJK fonts are split into unicode-range chunks so a page only downloads',
    '   the glyph ranges it renders. Do not edit by hand; run `bun run fonts:split`.',
    '   ========================================================================== */',
    '',
    ...results.flatMap(result => result.generated),
    '',
].join('\n')

writeFileSync(cssFile, css)

for (const result of results) {
    console.log(
        `${result.key}: ${result.chunks} chunks, ${(result.bytes / 1e6).toFixed(2)} MB, ` +
        `${result.blocks} @font-face rules`,
    )
}
console.log(`CSS: ${(Buffer.byteLength(css) / 1024).toFixed(1)} KB -> ${relative(root, cssFile)}`)
